<?php
/**
 * ============================================================================
 *  سامانه جامع مدیریت هنرستان شهید رجایی
 *  فایل: logout.php — خروج امن از سامانه
 * ----------------------------------------------------------------------------
 *  عملیات:
 *    ۱) ثبت رخداد خروج در گزارش فعالیت‌ها
 *    ۲) پاک‌سازی کامل داده‌های نشست و حذف کوکی نشست
 *    ۳) هدایت به صفحه ورود با پیام فارسی
 *
 *  نکته امنیتی: خروج با درخواست GET + توکن CSRF اختیاری انجام می‌شود؛
 *  برای جلوگیری از خروج اجباری (CSRF Logout) در صورت ارسال توکن نامعتبر،
 *  کاربر فقط به داشبورد بازمی‌گردد.
 * ============================================================================
 */

require __DIR__ . '/db.php';

hs_session_start();

/* ثبت خروج در گزارش فعالیت‌ها (قبل از تخریب نشست) */
if (hs_logged_in()) {
    $admin = current_admin();
    log_activity('خروج از سامانه', 'کاربر: ' . ($admin['username'] ?? '—'));
}

/* پاک‌سازی کامل نشست */
hs_logout();

/* شروع نشست تازه فقط برای نمایش پیام خروج */
hs_session_start();
flash_set('info', 'با موفقیت از سامانه خارج شدید. برای ادامه مجدداً وارد شوید.');

header('Location: index.php');
exit;
